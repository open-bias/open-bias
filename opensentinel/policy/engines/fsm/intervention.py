"""
Intervention handling for workflow constraint violations.

Simplified: messages come directly from constraint violations (generated by
the compiler from rule text). No separate interventions template map.
"""

import logging

from opensentinel.core.intervention.strategies import (
    InterventionConfig,
    StrategyType,
)
from opensentinel.policy.engines.fsm.workflow.constraints import ConstraintViolation

logger = logging.getLogger(__name__)


class InterventionHandler:
    """
    Builds InterventionConfig from constraint violations.

    Messages are stored on constraint objects (generated by the compiler
    from rule text). This handler wraps them in InterventionConfig for
    the interceptor layer.
    """

    def __init__(
        self,
        default_strategy: StrategyType = StrategyType.SYSTEM_PROMPT_APPEND,
        max_intervention_attempts: int = 3,
    ) -> None:
        self.default_strategy = default_strategy
        self.max_intervention_attempts = max_intervention_attempts

    def get_config_for_violation(
        self, violation: ConstraintViolation
    ) -> InterventionConfig:
        """Build an InterventionConfig from a constraint violation."""
        return InterventionConfig(
            strategy_type=self.default_strategy,
            message_template=violation.message,
            max_applications=self.max_intervention_attempts,
        )

    def get_message(self, violation: ConstraintViolation) -> str | None:
        """Get the intervention message from a violation."""
        return violation.message or None
